/// Spacing from Figma Foundations › Spacing & Radius › Spacing, named by pixel value.
/// Figma names steps the Tailwind way, so `spacing/4` is [px16], not [px4].
/// The trailing comment is the Figma token name.
abstract final class AppSpacing {
  static const double px2 = 2; // spacing/0-5
  static const double px4 = 4; // spacing/1
  static const double px6 = 6; // spacing/1-5
  static const double px8 = 8; // spacing/2
  static const double px12 = 12; // spacing/3
  static const double px16 = 16; // spacing/4
  static const double px20 = 20; // spacing/5
  static const double px24 = 24; // spacing/6
  static const double px32 = 32; // spacing/8
  static const double px40 = 40; // spacing/10
  static const double px48 = 48; // spacing/12
  static const double px64 = 64; // spacing/16
  static const double px80 = 80; // spacing/20
}
